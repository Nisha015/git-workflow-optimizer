"""Basic frontend checks: the HTML, CSS and JS are served and wired together.

These are static checks (no browser). Visual behaviour is verified manually,
see docs/SCREENSHOT_GUIDE.md and the manual checklist in README.md.
"""
import re
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
HTML = (ROOT / "templates" / "index.html").read_text(encoding="utf-8")
JS = (ROOT / "static" / "js" / "script.js").read_text(encoding="utf-8")


def test_static_files_are_served(client):
    assert client.get("/static/css/style.css").status_code == 200
    assert client.get("/static/js/script.js").status_code == 200


def test_page_has_required_sections(client):
    html = client.get("/").get_data(as_text=True)
    for element_id in ("overview", "workflows", "charts", "recommendation", "data", "devops",
                       "barChart", "radarChart", "metricCards", "workflowCards"):
        assert f'id="{element_id}"' in html
    assert "Simulated data" in html


def test_every_element_id_used_by_js_exists_in_html():
    used = set(re.findall(r'\$\("([A-Za-z0-9_]+)"\)', JS))
    used |= set(re.findall(r'\$\(`([A-Za-z0-9_]+)`\)', JS))
    created_dynamically = {"w_", "wv_"}  # slider ids are generated by JS
    missing = {i for i in used if i not in HTML and i not in created_dynamically}
    assert not missing, f"IDs used in script.js but absent from index.html: {missing}"


def test_js_calls_all_main_api_endpoints():
    for endpoint in ("/api/comparison", "/api/metrics", "/api/workflows",
                     "/api/recommendation", "/api/history"):
        assert endpoint in JS


def test_js_escapes_database_text():
    assert "function esc(" in JS and "textContent" in JS


@pytest.mark.skipif(shutil.which("node") is None, reason="Node.js not installed")
def test_javascript_syntax_is_valid():
    result = subprocess.run(["node", "--check", str(ROOT / "static" / "js" / "script.js")],
                            capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
